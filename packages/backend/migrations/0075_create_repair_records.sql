CREATE TABLE IF NOT EXISTS repair_records (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    bitrix_external_id BIGINT UNSIGNED NULL,
    display_name VARCHAR(255) NOT NULL,
    repair_kind VARCHAR(16) CHARACTER SET ascii NOT NULL,
    repair_status VARCHAR(32) CHARACTER SET ascii NOT NULL,
    repair_no BIGINT UNSIGNED NOT NULL,
    client_contact_id BIGINT UNSIGNED NULL,
    client_name VARCHAR(255) NOT NULL DEFAULT '',
    client_phone VARCHAR(64) NOT NULL DEFAULT '',
    device VARCHAR(255) NOT NULL DEFAULT '',
    model VARCHAR(255) NOT NULL DEFAULT '',
    serial_no VARCHAR(255) NOT NULL DEFAULT '',
    acceptance_point VARCHAR(255) NOT NULL DEFAULT '',
    appearance_text TEXT NOT NULL,
    defect_text TEXT NOT NULL,
    pay_type VARCHAR(16) CHARACTER SET ascii NOT NULL,
    service_cost DECIMAL(18,2) NULL,
    customer_price DECIMAL(18,2) NULL,
    deal_id BIGINT UNSIGNED NULL,
    task_id BIGINT UNSIGNED NULL,
    refusal_at DATETIME(6) NULL,
    refusal_reason TEXT NULL,
    refusal_by_id VARCHAR(191) NULL,
    refusal_by_name VARCHAR(255) NULL,
    refusal_deal_cancelled BOOLEAN NOT NULL DEFAULT FALSE,
    refusal_task_reframed BOOLEAN NOT NULL DEFAULT FALSE,
    repair_item_code VARCHAR(191) NULL,
    repair_store VARCHAR(255) NULL,
    issue_store VARCHAR(255) NULL,
    repair_delivery_note VARCHAR(191) NULL,
    product_id BIGINT UNSIGNED NULL,
    source_store VARCHAR(255) NULL,
    service_comment TEXT NOT NULL,
    internal_comment TEXT NOT NULL,
    source_created_at DATETIME(6) NULL,
    created_by_id VARCHAR(191) NOT NULL DEFAULT '',
    created_by_name VARCHAR(255) NOT NULL DEFAULT '',
    mutation_no INT UNSIGNED NOT NULL DEFAULT 0,
    last_state_hash BINARY(32) NOT NULL,
    deleted_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_repair_records_bitrix (bitrix_external_id),
    UNIQUE KEY uq_repair_records_number (repair_no),
    KEY ix_repair_records_status (repair_status, source_created_at),
    KEY ix_repair_records_deal (deal_id),
    KEY ix_repair_records_task (task_id),
    KEY ix_repair_records_deleted (deleted_at),
    CONSTRAINT chk_repair_records_bitrix CHECK (bitrix_external_id IS NULL OR bitrix_external_id > 0),
    CONSTRAINT chk_repair_records_number CHECK (repair_no > 0),
    CONSTRAINT chk_repair_records_kind CHECK (repair_kind IN ('client', 'presale')),
    CONSTRAINT chk_repair_records_status CHECK (repair_status IN ('received_tt', 'received_office', 'sent', 'sent_to_tt', 'ready_tt', 'issued', 'pre_office', 'pre_sent', 'pre_back_office', 'pre_to_point', 'pre_at_tt')),
    CONSTRAINT chk_repair_records_pay_type CHECK (pay_type IN ('warranty', 'paid')),
    CONSTRAINT chk_repair_records_prices CHECK (
        (pay_type = 'warranty' AND service_cost IS NULL AND customer_price IS NULL)
        OR (pay_type = 'paid' AND (service_cost IS NULL OR service_cost >= 0) AND (customer_price IS NULL OR customer_price >= 0))
    ),
    CONSTRAINT chk_repair_records_refusal CHECK (
        (refusal_at IS NULL AND refusal_reason IS NULL AND refusal_by_id IS NULL AND refusal_by_name IS NULL AND refusal_deal_cancelled = FALSE AND refusal_task_reframed = FALSE)
        OR (refusal_at IS NOT NULL AND refusal_reason IS NOT NULL AND CHAR_LENGTH(refusal_reason) > 0 AND refusal_by_id IS NOT NULL AND refusal_by_name IS NOT NULL)
    )
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
