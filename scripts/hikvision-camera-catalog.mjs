function attr(label, rawValue, {
	key = 'additional_characteristic',
	group = 'Дополнительно',
	type = 'text',
	normalizedValue = rawValue,
	numberValue = null,
	numberMin = null,
	numberMax = null,
	unit = '',
	booleanValue = null,
	filterable = false,
} = {}) {
	return {
		key,
		label,
		sourceLabel: label,
		group,
		type,
		rawValue,
		normalizedValue: String(normalizedValue),
		numberValue,
		numberMin,
		numberMax,
		unit,
		booleanValue,
		filterable,
		status: filterable ? 'Готово для фильтра' : 'Только для отображения',
	};
}

const yesNo = (label, value, options = {}) => attr(label, value ? 'Да' : 'Нет', {
	type: 'boolean',
	normalizedValue: value ? 'Да' : 'Нет',
	booleanValue: value,
	filterable: true,
	...options,
});

